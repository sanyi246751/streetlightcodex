-- Photo hand-off queue. A trigger creates a job after the browser has safely
-- uploaded a temporary object; the Edge Function moves it to Google Drive.
create table if not exists public.photo_transfers (
  id bigint generated by default as identity primary key,
  storage_path text not null unique,
  destination text not null check (destination in ('base-survey', 'replacement', 'repair')),
  record_id bigint not null,
  slot text not null,
  status text not null default 'pending' check (status in ('pending', 'processing', 'drive_uploaded', 'failed', 'completed')),
  attempts integer not null default 0,
  last_error text,
  drive_file_id text,
  drive_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);
create index if not exists photo_transfers_ready_idx on public.photo_transfers (status, created_at);

