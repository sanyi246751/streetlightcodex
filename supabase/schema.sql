-- Jobs are created only by the storage trigger and handled using the Edge
-- Function service key; browsers must not be able to read or alter this queue.

-- Trigger an asynchronous attempt immediately after each accepted upload.  The
-- once-per-minute Cron job remains the durable retry path for failed jobs.
create or replace function public.request_photo_drive_sync()
returns void language plpgsql security definer set search_path = public, net, vault as $$
begin
  perform net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets where name = 'photo_sync_project_url') || '/functions/v1/photo-drive-sync',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-photo-sync-secret',
      (select decrypted_secret from vault.decrypted_secrets where name = 'photo_sync_cron_secret')),
    body := '{}'::jsonb,
    timeout_milliseconds := 55000
  );
exception when others then
  raise warning 'Could not start immediate photo sync: %', sqlerrm;
end $$;

create or replace function public.queue_streetlight_photo()
returns trigger language plpgsql security definer set search_path = public as $$
declare m text[]; target_record_id bigint; target_destination text; target_slot text;
begin
  if new.bucket_id <> 'streetlight-photos' then return new; end if;
  m := regexp_match(new.name, '^repair-reports/(.+)_(before|after)[.][^/]+$');
  if m is not null then
    select id into target_record_id from repair_reports where streetlight_id = m[1]
    order by repaired_at desc nulls last, id desc limit 1;
    target_destination := 'repair'; target_slot := case when m[2] = 'before' then '0-pre' else '0-post' end;
  else
    m := regexp_match(new.name, '^base-surveys/(.+)_(before|after)[.][^/]+$');
    if m is not null then
      select id into target_record_id from base_surveys where streetlight_id = m[1]
      order by created_at desc, id desc limit 1;
      target_destination := 'base-survey'; target_slot := case when m[2] = 'before' then 'before' else 'after' end;
    else return new;
    end if;
  end if;
  if target_record_id is null then raise warning 'No record found for uploaded photo %', new.name; return new; end if;
  insert into photo_transfers(storage_path, destination, record_id, slot)
  values (new.name, target_destination, target_record_id, target_slot)
  on conflict (storage_path) do update set destination = excluded.destination, record_id = excluded.record_id,
    slot = excluded.slot, status = 'pending', attempts = 0, last_error = null, drive_file_id = null,
    drive_url = null, completed_at = null, updated_at = now();
  perform public.request_photo_drive_sync();
  return new;
end $$;
drop trigger if exists queue_streetlight_photo_after_upload on storage.objects;
create trigger queue_streetlight_photo_after_upload after insert or update on storage.objects
for each row execute function public.queue_streetlight_photo();

create or replace function public.claim_photo_transfers(batch_size integer default 10)
returns setof public.photo_transfers language sql security definer set search_path = public as $$
  with candidates as (
    select id from photo_transfers
    where status in ('pending', 'failed', 'drive_uploaded')
       or (status = 'processing' and updated_at < now() - interval '10 minutes')
    order by created_at for update skip locked limit greatest(1, least(batch_size, 25))
  ), claimed as (
    update photo_transfers p set status = case when p.status = 'drive_uploaded' then 'drive_uploaded' else 'processing' end, attempts = attempts + 1,
      updated_at = now(), last_error = null
    from candidates c where p.id = c.id returning p.*
  ) select * from claimed;
$$;

create or replace function public.finish_photo_transfer(job_id bigint, file_id text, file_url text)
returns void language plpgsql security definer set search_path = public as $$
declare job photo_transfers;
declare photo_index integer;
begin
  select * into job from photo_transfers where id = job_id for update;
  if not found then raise exception 'Photo job % not found', job_id; end if;
  if job.destination = 'base-survey' then
    update base_surveys set before_photo_url = case when job.slot = 'before' then file_url else before_photo_url end,
      after_photo_url = case when job.slot = 'after' then file_url else after_photo_url end where id = job.record_id;
  elsif job.destination = 'replacement' then
    update replacement_history set photo_url = file_url where id = job.record_id;
  else
    photo_index := (regexp_match(job.slot, '^([0-9]+)-(pre|post)$'))[1]::integer * 2
      + case when job.slot like '%-post' then 1 else 0 end;
    update repair_reports set metadata = jsonb_set(metadata, array['photos', photo_index::text], to_jsonb(file_url), true)
      where id = job.record_id;
  end if;
  update photo_transfers set status = 'completed', drive_file_id = file_id, drive_url = file_url,
    completed_at = now(), updated_at = now(), last_error = null where id = job_id;
end $$;

create or replace function public.record_drive_upload(job_id bigint, file_id text, file_url text)
returns void language sql security definer set search_path = public as $$
  update photo_transfers set status = 'drive_uploaded', drive_file_id = file_id, drive_url = file_url,
    updated_at = now(), last_error = null where id = job_id;
$$;

create or replace function public.fail_photo_transfer(job_id bigint, error_message text)
returns void language sql security definer set search_path = public as $$
  update photo_transfers set status = case when drive_file_id is not null then 'drive_uploaded' else 'failed' end,
    last_error = left(error_message, 2000), updated_at = now()
  where id = job_id;
$$;
